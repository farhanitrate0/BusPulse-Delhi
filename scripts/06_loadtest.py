"""Stress test + edge cases against a running server.

    python run.py                                   (in another terminal)
    python scripts/06_loadtest.py --url http://127.0.0.1:8000 --n 200 --c 10
Writes docs/stress_results.md.
"""
from __future__ import annotations

import argparse
import json
import random
import sys
import time
import urllib.error
import urllib.parse
import urllib.request
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import config  # noqa: E402


def get(url: str, timeout=60):
    t = time.time()
    try:
        with urllib.request.urlopen(url, timeout=timeout) as r:
            body = r.read()
            return r.status, time.time() - t, json.loads(body) if body[:1] in (b"{", b"[") else None
    except urllib.error.HTTPError as e:
        body = e.read()
        try:
            j = json.loads(body)
        except Exception:  # noqa: BLE001
            j = None
        return e.code, time.time() - t, j
    except Exception as e:  # noqa: BLE001
        return 0, time.time() - t, {"error": str(e)}


def q(base, **kw):
    return base + "/journeys?" + urllib.parse.urlencode(kw)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--url", default="http://127.0.0.1:8000")
    ap.add_argument("--n", type=int, default=200)
    ap.add_argument("--c", type=int, default=10)
    a = ap.parse_args()
    from app import gtfs as gtfs_mod
    g = gtfs_mod.load()
    rng = random.Random(1)
    served = [i for i, p in enumerate(g["cl_lat"])]
    urls = []
    for _ in range(a.n):
        i, j = rng.sample(served, 2)
        h, m = rng.randint(5, 23), rng.choice([0, 15, 30, 45])
        day = rng.choice([25, 26, 27, 28, 29, 30, 31])
        urls.append(q(a.url, **{"from": f"{g['cl_lat'][i]:.5f},{g['cl_lon'][i]:.5f}",
                                "to": f"{g['cl_lat'][j]:.5f},{g['cl_lon'][j]:.5f}",
                                "depart": f"2026-10-{day}T{h:02d}:{m:02d}",
                                "mode": rng.choice(["fastest", "balanced", "comfortable"])}))
    get(urls[0])  # warm
    # one user at a time (what a single rider / judge clicking around sees)
    seq = np.array([get(u)[1] for u in urls[:50]]) * 1000
    t0 = time.time()
    with ThreadPoolExecutor(a.c) as ex:
        res = list(ex.map(get, urls))
    wall = time.time() - t0
    codes = [r[0] for r in res]
    lat = np.array([r[1] for r in res]) * 1000
    found = sum(1 for r in res if r[0] == 200 and r[2] and r[2].get("options"))
    errors5xx = sum(1 for c in codes if c >= 500 or c == 0)
    lines = ["# Stress test (auto-generated by scripts/06_loadtest.py)\n",
             f"**One user at a time** (50 random queries): p50 {np.percentile(seq, 50):.0f} ms, "
             f"p95 {np.percentile(seq, 95):.0f} ms, max {seq.max():.0f} ms per complete journey plan "
             "(3 options, 24-hour profile, crowding, reliability range).\n",
             "**Under load** — one Python process answers requests one after another, so with 10 users at once "
             "each waits for the others (scale out with more workers/instances):\n",
             f"{a.n} random journey queries (random stop-to-stop pairs anywhere in Delhi, random hour 05–23, "
             f"held-out dates, all three modes), {a.c} concurrent clients, one local server process.\n",
             "| metric | value |", "|---|---|",
             f"| throughput | {a.n / wall:.1f} requests/s |", f"| latency p50 | {np.percentile(lat, 50):.0f} ms |",
             f"| latency p95 | {np.percentile(lat, 95):.0f} ms |", f"| latency max | {lat.max():.0f} ms |",
             f"| HTTP 200 | {codes.count(200)} |", f"| server errors (5xx / no response) | {errors5xx} |",
             f"| journeys found | {found} ({100 * found / a.n:.0f} %) |"]
    edge = [
        ("no stop within walking distance (field near Delhi border)", q(a.url, **{"from": "28.88,76.85", "to": "Nehru Place"})),
        ("2 am query (no service)", q(a.url, **{"from": "Kashmere Gate", "to": "Nehru Place", "depart": "2026-10-27T02:00"})),
        ("invalid coordinates", q(a.url, **{"from": "999,999", "to": "Nehru Place"})),
        ("outside Delhi (Mumbai)", q(a.url, **{"from": "19.07,72.87", "to": "Nehru Place"})),
        ("same origin and destination", q(a.url, **{"from": "Nehru Place", "to": "Nehru Place"})),
        ("unknown stop name", q(a.url, **{"from": "zzqqxx", "to": "Nehru Place"})),
        ("bad time format", q(a.url, **{"from": "Kashmere Gate", "to": "Nehru Place", "depart": "tomorrow-ish"})),
        ("bad mode", q(a.url, **{"from": "Kashmere Gate", "to": "Nehru Place", "mode": "teleport"})),
        ("missing 'to'", a.url + "/journeys?from=Nehru%20Place"),
        ("very short trip (300 m)", q(a.url, **{"from": "28.5494,77.2519", "to": "28.5520,77.2519"})),
        ("typo in stop name", q(a.url, **{"from": "kashmiri gate", "to": "nehru plce"})),
        ("injection-like text", q(a.url, **{"from": "<script>alert(1)</script>", "to": "'; DROP TABLE stops;--"})),
        ("matrix 3×3", a.url + "/matrix?" + urllib.parse.urlencode({"origins": "Kashmere Gate|ITO|Saket",
                                                                     "destinations": "Nehru Place|Karol Bagh|AIIMS"})),
        ("traffic bad hour", a.url + "/traffic?hour=25"),
    ]
    lines += ["\n## Edge cases\n", "| case | HTTP | response |", "|---|---|---|"]
    for name, u in edge:
        code, dt, j = get(u)
        if j is None:
            msg = ""
        elif "message" in j:
            msg = j["message"]
        elif "detail" in j:
            msg = str(j["detail"])[:120]
        elif "options" in j:
            msg = f"{len(j['options'])} options; warnings: {'; '.join(j.get('warnings', [])) or '—'}"
        else:
            msg = "ok"
        lines.append(f"| {name} | {code} | {str(msg).replace('|', '/')[:160]} |")
    (config.DOCS_DIR / "stress_results.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
