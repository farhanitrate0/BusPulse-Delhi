"""Operator insights from the GPS model → data/model/insights.json, docs/INSIGHTS.md, docs/img/speed_by_hour.png

* city bus speed by hour (weekday / Saturday / Sunday)
* slowest stretches at 18:00 weekday vs 23:00
* routes whose real (GPS) running time is furthest from the timetable at the evening peak
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import config  # noqa: E402
from app import gtfs as gtfs_mod  # noqa: E402
from app.traveltime import TravelTimeModel  # noqa: E402


def main():
    g = gtfs_mod.load()
    tt = TravelTimeModel(g)
    if not tt.has_gps:
        sys.exit("run scripts/02_build_traveltime.py first")
    names = g["cl_name"]
    city = pd.read_parquet(config.MODEL_DIR / "city_hour.parquet")
    sp = city.pivot(index="h", columns="dt", values="speed_kmh")
    peak, night = 18, 23
    ok = (tt.N[:, 0, peak] >= 8) & (tt.N[:, 0, night] >= 3) & (tt.dist >= 250)
    idx = np.nonzero(ok)[0]
    spd_peak = tt.dist[idx] / tt.RUN[idx, 0, peak] * 3.6
    spd_night = tt.dist[idx] / tt.RUN[idx, 0, night] * 3.6
    order = np.argsort(spd_peak)[:25]
    slow = [{"stretch": f"{names[g['pairs'][idx[i]][0]]} → {names[g['pairs'][idx[i]][1]]}",
             "peak_kmh": round(float(spd_peak[i]), 1), "night_kmh": round(float(spd_night[i]), 1),
             "obs_peak": int(tt.N[idx[i], 0, peak]),
             "lat": float(g["cl_lat"][g["pairs"][idx[i]][0]]), "lon": float(g["cl_lon"][g["pairs"][idx[i]][0]])}
            for i in order]
    gaps = []
    for p in g["patterns"]:
        prs = p["pairs"]
        if len(prs) < 10 or p["n_trips"] < 5:
            continue
        cover = float((tt.LEVEL[prs, 0, peak] >= 2).mean())
        if cover < 0.7:
            continue
        gps = tt.chain_time(prs, 0, peak * 3600)
        sched = float(p["off"][-1] - p["off"][0])
        if sched <= 0:
            continue
        gaps.append({"route": p["name"], "from": names[int(p["cl"][0])], "to": names[int(p["cl"][-1])],
                     "stops": len(p["cl"]), "timetable_min": round(sched / 60), "gps_min": round(gps / 60),
                     "gps_night_min": round(tt.chain_time(prs, 0, night * 3600) / 60),
                     "ratio": round(gps / sched, 2), "gps_coverage_pct": round(100 * cover)})
    gaps.sort(key=lambda r: -r["ratio"])
    seen, gap_top = set(), []
    for r in gaps:
        if r["route"] in seen:
            continue
        seen.add(r["route"])
        gap_top.append(r)
    allr = np.array([r["ratio"] for r in gaps]) if gaps else np.array([np.nan])
    ins = {
        "headline": {"peak_speed_kmh": round(float(sp.loc[peak, 0]), 1) if peak in sp.index else None,
                     "night_speed_kmh": round(float(sp.loc[night, 0]), 1) if night in sp.index else None,
                     "timetable_gap_pct": round(100 * (float(np.nanmedian(allr)) - 1)),
                     "routes_compared": len(gaps)},
        "speed_by_hour": {config.DAYTYPES[int(d)]: [None if pd.isna(v) else round(float(v), 1)
                                                    for v in sp[d].reindex(range(24))] for d in sp.columns},
        "slowest_peak": slow, "timetable_gap_routes": gap_top[:20],
    }
    (config.MODEL_DIR / "insights.json").write_text(json.dumps(ins, indent=1), encoding="utf-8")
    md = ["# Operator insights (auto-generated by scripts/07_insights.py)\n",
          f"- Weekday median bus speed: **{ins['headline']['peak_speed_kmh']} km/h at 18:00** vs "
          f"**{ins['headline']['night_speed_kmh']} km/h at 23:00** (straight-line stop-to-stop speed incl. stops).",
          f"- At the weekday evening peak, the median route takes **{ins['headline']['timetable_gap_pct']:+d}%** "
          f"versus its timetable ({len(gaps)} routes with ≥70 % GPS coverage).\n",
          "## Slowest stretches, weekday 18:00 (vs 23:00)\n", "| # | stretch | 18:00 km/h | 23:00 km/h | obs |", "|---|---|---|---|---|"]
    md += [f"| {i+1} | {s['stretch']} | {s['peak_kmh']} | {s['night_kmh']} | {s['obs_peak']} |" for i, s in enumerate(slow[:20])]
    md += ["\n## Timetable vs reality, weekday 18:00\n", "| route | from → to | stops | timetable | GPS 18:00 | GPS 23:00 |",
           "|---|---|---|---|---|---|"]
    md += [f"| {r['route']} | {r['from']} → {r['to']} | {r['stops']} | {r['timetable_min']} min | {r['gps_min']} min | {r['gps_night_min']} min |"
           for r in gap_top[:20]]
    (config.DOCS_DIR / "INSIGHTS.md").write_text("\n".join(md), encoding="utf-8")
    print("\n".join(md[:4]))
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
        fig, ax = plt.subplots(figsize=(8, 3.6))
        for d, c in zip(sp.columns, ["#0b6e4f", "#e39b00", "#3b6ea8"]):
            ax.plot(sp.index, sp[d], label=config.DAYTYPES[int(d)], color=c, lw=2)
        ax.set_xlabel("hour (IST)"); ax.set_ylabel("median bus speed, km/h"); ax.set_xticks(range(0, 24, 2))
        ax.set_title("Delhi bus speed by hour (from GPS)"); ax.legend(frameon=False); ax.grid(alpha=.3)
        fig.tight_layout()
        (config.DOCS_DIR / "img").mkdir(exist_ok=True)
        fig.savefig(config.DOCS_DIR / "img" / "speed_by_hour.png", dpi=120)
    except ImportError:
        pass


if __name__ == "__main__":
    main()
