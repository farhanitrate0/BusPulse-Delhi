"""Collect per-day GPS quality stats (data/segments/quality_*.json) → docs/DATA_QUALITY.md"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import config  # noqa: E402
from app import gtfs as gtfs_mod  # noqa: E402


def main():
    rows = []
    for f in sorted(config.SEG_DIR.glob("quality_*.json")):
        rows.append(json.loads(f.read_text()))
    if not rows:
        sys.exit("no quality files yet")
    q = pd.DataFrame(rows).sort_values("day")
    tot = q.sum(numeric_only=True)
    pct = lambda a, b: f"{100 * a / max(b, 1):.1f} %"  # noqa: E731
    g = gtfs_mod.load()
    md = ["# GPS data quality (auto-generated by scripts/08_data_quality.py)\n",
          f"Days processed: {len(q)} ({', '.join(str(int(d)) for d in q.day)} Oct).\n",
          "## Cleaning funnel (all processed days)\n", "| step | rows | share |", "|---|---|---|",
          f"| raw rows | {int(tot.rows_total):,} | 100 % |",
          f"| unparseable (lat/lng/timestamp/vehicle) | {int(tot.rows_invalid):,} | {pct(tot.rows_invalid, tot.rows_total)} |",
          f"| outside Delhi bounding box | {int(tot.rows_out_bbox):,} | {pct(tot.rows_out_bbox, tot.rows_total)} |",
          f"| duplicate (vehicle, timestamp) | {int(tot.rows_duplicates):,} | {pct(tot.rows_duplicates, tot.rows_total)} |",
          f"| GPS jumps removed (in & out speed > 100 km/h) | {int(tot.spikes_removed):,} | {pct(tot.spikes_removed, tot.rows_total)} |",
          f"| clean fixes | {int(tot.rows_dedup - tot.spikes_removed):,} | {pct(tot.rows_dedup - tot.spikes_removed, tot.rows_total)} |",
          f"| gaps > {config.DATA_GAP_S} s between fixes of a bus | {int(tot.gaps_gt_180s):,} | |",
          f"| interpolated points added (fast buses, ≤ 1.5 km gaps) | {int(tot.points_densified):,} | |",
          "\n## From fixes to stop-to-stop observations\n", "| step | count | share of candidates |", "|---|---|---|",
          f"| stop visits detected | {int(tot.visits):,} | |",
          f"| consecutive visit pairs (candidates) | {int(tot.seg_candidates):,} | 100 % |",
          f"| dropped: stops not adjacent on any GTFS route (missed stop / detour / crossing road) | {int(tot.seg_drop_not_adjacent):,} | {pct(tot.seg_drop_not_adjacent, tot.seg_candidates)} |",
          f"| dropped: data gap inside the stretch | {int(tot.seg_drop_data_gap):,} | {pct(tot.seg_drop_data_gap, tot.seg_candidates)} |",
          f"| dropped: implausible speed (< 3 or > 70 km/h) or > 30 min | {int(tot.seg_drop_speed_or_time):,} | {pct(tot.seg_drop_speed_or_time, tot.seg_candidates)} |",
          f"| **kept** | **{int(tot.seg_kept):,}** | **{pct(tot.seg_kept, tot.seg_candidates)}** |",
          "\n## Per day\n", "| day | raw rows | vehicles | median fix interval s | dup % | segments kept | route_id in GTFS % | time s |",
          "|---|---|---|---|---|---|---|---|"]
    for r in q.itertuples():
        md.append(f"| {int(r.day)} | {int(r.rows_total):,} | {int(r.vehicles):,} | {r.median_sampling_interval_s} | "
                  f"{100*r.rows_duplicates/max(r.rows_total,1):.1f} | {int(r.seg_kept):,} | {r.gps_route_ids_in_gtfs_pct} | {r.total_s} |")
    md += ["\n## GTFS\n", "```", json.dumps(g["stats"], indent=1), "```"]
    mm = config.MODEL_DIR / "model_meta.json"
    if mm.exists():
        md += ["\n## Model coverage\n", "```", mm.read_text(), "```"]
    cm = config.MODEL_DIR / "crowd_meta.json"
    if cm.exists():
        m = json.loads(cm.read_text())
        md += ["\n## Ticket matching\n", "```", json.dumps({k: m[k] for k in ("tickets_total", "route_match_pct",
               "stop_match_pct_of_tickets", "week_to_week_correlation", "ac_share_pct") if k in m}, indent=1), "```"]
    (config.DOCS_DIR / "DATA_QUALITY.md").write_text("\n".join(md), encoding="utf-8")
    print("\n".join(md[:20]))


if __name__ == "__main__":
    main()
